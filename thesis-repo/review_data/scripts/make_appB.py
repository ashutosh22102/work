import json
from openpyxl import load_workbook

inc = {r[0]: r for r in load_workbook("SLR_Search_and_Screening.xlsx")["Included studies"].iter_rows(min_row=2, values_only=True)}
km = json.load(open("keymap.json"))
F = json.load(open("final.json", encoding="utf-8"))
ex = {}
for l in open("extraction.txt", encoding="utf-8"):
    if l.startswith("#") or not l.strip():
        continue
    p = l.rstrip("\n").split("|")
    ex[p[0]] = p

DL = {"Survey": "Survey", "Conceptual": "Concept.", "Qualitative/case": "Qual./case", "Panel/archival": "Panel", "Mixed": "Mixed", "Formal model": "Model"}
OL = {"SCA": "SCA", "CA": "CA", "FP": "FP", "INNOV": "Innov.", "RES": "Resil.", "BMI": "BMI", "OTHER": "Other"}
Q7 = {"yes": "yes", "no": "no", "not_assessable": "n.a."}
esc = lambda s: (s or "-").replace("&", "\\&").replace("%", "\\%")
rows = sorted(inc, key=lambda i: (0 if F[i]["tier"] == "Core" else 1, (inc[i][3] or "").lower(), str(inc[i][4])))
head = r"\textbf{ID} & \textbf{Study} & \textbf{Design} & \textbf{Context} & \textbf{Outcome} & \textbf{Score} & \textbf{Q7} & \textbf{VHB} \\"
L = [r"""% Appendix B - overview of the included studies (referenced in Section 4.1); generated by make_appB.py
\chapter{Overview of the Included Studies}
\label{AppendixB}

The table lists all 109 studies included in the systematic review, ordered by tier and author. Design: Concept.\ = conceptual, Qual./case = qualitative or case study, Panel = panel or archival data, Mixed = mixed methods, Model = formal model. Outcome: FP = firm performance, CA = competitive advantage, SCA = sustainable competitive advantage, BMI = business model innovation, Innov.\ = innovation, Resil.\ = resilience. Score: quality score on criteria Q1--Q6 of Table~\ref{tab:quality} (0--6). Q7: limitations discussed (yes, no, n.a.\ = not assessable from the abstract). IDs marked with an asterisk were checked against the full text; all other codes are based on the abstract. VHB: journal listed in the VHB Rating 2024 (descriptive only).

{\footnotesize\setstretch{1.0}\sloppy
\begin{longtable}{>{\raggedright\arraybackslash}p{0.95cm}>{\raggedright\arraybackslash}p{3.25cm}>{\raggedright\arraybackslash}p{1.7cm}>{\raggedright\arraybackslash}p{2.45cm}>{\raggedright\arraybackslash}p{1.55cm}>{\centering\arraybackslash}p{1.15cm}>{\centering\arraybackslash}p{0.75cm}>{\centering\arraybackslash}p{0.75cm}}
\toprule
""" + head + r"""
\midrule
\endfirsthead
\toprule
""" + head + r"""
\midrule
\endhead
\bottomrule
\endfoot"""]
cur = None
for i in rows:
    f = F[i]
    if f["tier"] != cur:
        cur = f["tier"]
        label = "Core (e-commerce and platforms)" if cur == "Core" else "Supporting (other industries)"
        L.append("\\multicolumn{8}{l}{\\textbf{%s studies (n = %d)}} \\\\ \\addlinespace" % (label, sum(1 for k in F if F[k]["tier"] == cur)))
    k = km[i]
    L.append("%s & \\textcite[%s]{%s} & %s & %s & %s & %d & %s & %s \\\\" % (i + ("*" if f["evidence"] == "Full text" else ""), k["page"], k["key"], DL[f["design"]],
             esc(ex[i][4]), OL[f["outcome"]], f["q16"], Q7[f["q7"]], "yes" if inc[i][11] == "yes" else "no"))
L.append("\\end{longtable}}")
open("../thesis/Appendices/AppendixB.tex", "w", encoding="utf-8").write("\n".join(L) + "\n")
print(len(rows), sum(1 for x in L if "\\textcite[" in x))
